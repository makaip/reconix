/*
 * nftables ruleset generator — the BLUNT L3/L4 floor beneath the proxy.
 *
 * Reads a ScopeConfig JSON, compiles it (same compiler as the proxy and the
 * per-tool checker), and emits an nft ruleset from `CompiledScope.nftRules`:
 *   - default policy DROP on the output chain (deny by default),
 *   - accept only to compiled target CIDRs on their ports,
 *   - DNS (udp/tcp 53) allowed ONLY to a single configured internal resolver —
 *     every other :53 packet is dropped and counted (blocks DNS exfil),
 *   - everything else dies on the policy drop (raw sockets included).
 *
 * This is address-based: host-only targets (DNS names) produce no accept here;
 * their names are resolved and enforced at the proxy. In the compose topology
 * the container's only real route out is the proxy, so the practical floor is
 * "accept to the proxy + the model endpoint, drop the rest" — set RESOLVER and
 * the proxy/model CIDRs accordingly.
 *
 * RUNS INSIDE THE LINUX CONTAINER ONLY. The dev host is darwin (macOS) and has
 * no nftables — see README.md.
 *
 * Usage:
 *   npx tsx infra/nftables/generate.ts <scope.json> [resolverIp] > reconix.nft
 */

import { readFileSync } from 'node:fs'
import type { ScopeConfig } from '../../src/shared/scope'
import { compileScope } from '../../src/main/scope'

const scopePath = process.argv[2]
const resolver = process.argv[3] ?? process.env.DNS_RESOLVER ?? '127.0.0.11' // docker embedded DNS

if (!scopePath) {
  process.stderr.write('usage: tsx generate.ts <scope.json> [resolverIp]\n')
  process.exit(2)
}

const config = JSON.parse(readFileSync(scopePath, 'utf8')) as ScopeConfig
const compiled = compileScope(config)

const lines: string[] = []
lines.push('#!/usr/sbin/nft -f')
lines.push('# GENERATED by infra/nftables/generate.ts — do not hand-edit.')
lines.push(`# engagement: ${compiled.engagementId}`)
lines.push('flush ruleset')
lines.push('')
lines.push('table inet reconix_scope {')
lines.push('  chain output {')
lines.push('    type filter hook output priority 0; policy drop;')
lines.push('')
lines.push('    # Allow loopback and already-established flows.')
lines.push('    oif "lo" accept')
lines.push('    ct state established,related accept')
lines.push('')
lines.push('    # DNS only to the one internal resolver; drop+count all other :53')
lines.push('    # (this is where DNS-exfil attempts die).')
lines.push(`    ip daddr ${resolver} udp dport 53 accept`)
lines.push(`    ip daddr ${resolver} tcp dport 53 accept`)
lines.push('    udp dport 53 counter drop')
lines.push('    tcp dport 53 counter drop')
lines.push('')
lines.push('    # Compiled in-scope destinations (accept rules from CompiledScope.nftRules).')

let acceptCount = 0
for (const rule of compiled.nftRules) {
  if (rule.action !== 'accept' || !rule.cidr) continue
  acceptCount++
  const fam = rule.cidr.includes(':') ? 'ip6' : 'ip'
  const ports = rule.ports && rule.ports.length ? rule.ports : [80, 443]
  const portSet = `{ ${ports.join(', ')} }`
  lines.push(`    ${fam} daddr ${rule.cidr} tcp dport ${portSet} counter accept`)
}
if (acceptCount === 0) {
  lines.push('    # (no CIDR targets in scope — all egress except DNS-to-resolver drops)')
}

lines.push('')
lines.push('    # Everything else — non-target addresses, raw sockets, other protocols —')
lines.push('    # falls through to the policy drop above. This is the catch-all drop')
lines.push('    # (CompiledScope.nftRules ends in {action:"drop"}).')
lines.push('    counter drop')
lines.push('  }')
lines.push('}')
lines.push('')

process.stdout.write(lines.join('\n'))
